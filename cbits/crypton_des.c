#define ROTL32(v, k) (((v) << (k)) | ((v) >> (32 - (k))))

static inline uint64_t load_be64(const uint8_t *p)
{
	return ((uint64_t) p[0] << 56) | ((uint64_t) p[1] << 48)
	     | ((uint64_t) p[2] << 40) | ((uint64_t) p[3] << 32)
	     | ((uint64_t) p[4] << 24) | ((uint64_t) p[5] << 16)
	     | ((uint64_t) p[6] << 8)  | ((uint64_t) p[7]);
}

static inline void store_be64(uint8_t *p, uint64_t v)
{
	p[0] = (uint8_t) (v >> 56); p[1] = (uint8_t) (v >> 48);
	p[2] = (uint8_t) (v >> 40); p[3] = (uint8_t) (v >> 32);
	p[4] = (uint8_t) (v >> 24); p[5] = (uint8_t) (v >> 16);
	p[6] = (uint8_t) (v >> 8);  p[7] = (uint8_t) v;
}

/* bit i of v, numbered from 1 at the most significant end, as FIPS 46-3 does */
static inline uint32_t bit_of(uint64_t v, int i, int width)
{
	return (uint32_t) ((v >> (width - i)) & 1);
}

static const uint8_t PC1[56] = {
	57,49,41,33,25,17,9,1,58,50,42,34,26,18,10,2,59,51,43,35,27,
	19,11,3,60,52,44,36,63,55,47,39,31,23,15,7,62,54,46,38,30,22,
	14,6,61,53,45,37,29,21,13,5,28,20,12,4
};

static const uint8_t PC2[48] = {
	14,17,11,24,1,5,3,28,15,6,21,10,23,19,12,4,26,8,16,7,27,20,13,2,
	41,52,31,37,47,55,30,40,51,45,33,48,44,49,39,56,34,53,46,42,50,36,29,32
};

static const uint8_t SHIFTS[16] = { 1,1,2,2,2,2,2,2,1,2,2,2,2,2,2,1 };

void crypton_des_init(crypton_des_key *ks, const uint8_t *key, int reverse)
{
	uint64_t k = load_be64(key);
	uint64_t cd = 0;
	uint32_t c, d;
	int round, i;

	for (i = 0; i < 56; i++)
		cd = (cd << 1) | bit_of(k, PC1[i], 64);
	c = (uint32_t) (cd >> 28);
	d = (uint32_t) (cd & 0x0fffffffU);

	for (round = 0; round < 16; round++) {
		uint64_t merged;
		uint8_t *sk;
		int s = SHIFTS[round];

		c = ((c << s) | (c >> (28 - s))) & 0x0fffffffU;
		d = ((d << s) | (d >> (28 - s))) & 0x0fffffffU;
		merged = ((uint64_t) c << 28) | d;

		sk = ks->sk + (reverse ? (15 - round) : round) * 8;
		memset(sk, 0, 8);
		for (i = 0; i < 48; i++)
			sk[i / 6] = (uint8_t) ((sk[i / 6] << 1) | bit_of(merged, PC2[i], 56));
	}
}

static inline uint32_t des_f(uint32_t r, const uint8_t *sk)
{
	return SP[0][((ROTL32(r, 31) >> 26) & 0x3f) ^ sk[0]]
	     | SP[1][((ROTL32(r,  3) >> 26) & 0x3f) ^ sk[1]]
	     | SP[2][((ROTL32(r,  7) >> 26) & 0x3f) ^ sk[2]]
	     | SP[3][((ROTL32(r, 11) >> 26) & 0x3f) ^ sk[3]]
	     | SP[4][((ROTL32(r, 15) >> 26) & 0x3f) ^ sk[4]]
	     | SP[5][((ROTL32(r, 19) >> 26) & 0x3f) ^ sk[5]]
	     | SP[6][((ROTL32(r, 23) >> 26) & 0x3f) ^ sk[6]]
	     | SP[7][((ROTL32(r, 27) >> 26) & 0x3f) ^ sk[7]];
}

static inline uint64_t des_block(uint64_t b, const uint8_t *sk)
{
	uint32_t l, r;
	int round;

	l = IPL[0][(b >> 56) & 0xff] | IPL[1][(b >> 48) & 0xff]
	  | IPL[2][(b >> 40) & 0xff] | IPL[3][(b >> 32) & 0xff]
	  | IPL[4][(b >> 24) & 0xff] | IPL[5][(b >> 16) & 0xff]
	  | IPL[6][(b >>  8) & 0xff] | IPL[7][ b        & 0xff];
	r = IPR[0][(b >> 56) & 0xff] | IPR[1][(b >> 48) & 0xff]
	  | IPR[2][(b >> 40) & 0xff] | IPR[3][(b >> 32) & 0xff]
	  | IPR[4][(b >> 24) & 0xff] | IPR[5][(b >> 16) & 0xff]
	  | IPR[6][(b >>  8) & 0xff] | IPR[7][ b        & 0xff];

	for (round = 0; round < 16; round++) {
		uint32_t t = r;
		r = l ^ des_f(r, sk + round * 8);
		l = t;
	}

	{
		/* the preoutput is the halves the other way round */
		uint64_t p = ((uint64_t) r << 32) | l;
		return ((uint64_t) (FPH[0][(p >> 56) & 0xff] | FPH[1][(p >> 48) & 0xff]
		                  | FPH[2][(p >> 40) & 0xff] | FPH[3][(p >> 32) & 0xff]
		                  | FPH[4][(p >> 24) & 0xff] | FPH[5][(p >> 16) & 0xff]
		                  | FPH[6][(p >>  8) & 0xff] | FPH[7][ p        & 0xff]) << 32)
		     | (FPL[0][(p >> 56) & 0xff] | FPL[1][(p >> 48) & 0xff]
		      | FPL[2][(p >> 40) & 0xff] | FPL[3][(p >> 32) & 0xff]
		      | FPL[4][(p >> 24) & 0xff] | FPL[5][(p >> 16) & 0xff]
		      | FPL[6][(p >>  8) & 0xff] | FPL[7][ p        & 0xff]);
	}
}

/* Run every stage of the schedule over each block: one stage is DES, three are
 * EDE or EEE depending on the directions the schedules were built for. */
void crypton_des_ecb(uint8_t *out, const crypton_des_key *ks, uint32_t nkeys,
                     const uint8_t *in, uint32_t nblocks)
{
	uint32_t i, s;

	for (i = 0; i < nblocks; i++) {
		uint64_t b = load_be64(in + 8 * i);
		for (s = 0; s < nkeys; s++)
			b = des_block(b, ks[s].sk);
		store_be64(out + 8 * i, b);
	}
}
