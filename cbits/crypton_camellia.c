static const uint64_t SIGMA[6] = {
	0xA09E667F3BCC908BULL, 0xB67AE8584CAA73B2ULL, 0xC6EF372FE94F82BEULL,
	0x54FF53A5F1D36F1CULL, 0x10E527FADE682D1DULL, 0xB05688C2B3E6C1FDULL
};

static inline uint64_t load_be64(const uint8_t *p)
{
	return ((uint64_t) p[0] << 56) | ((uint64_t) p[1] << 48)
	     | ((uint64_t) p[2] << 40) | ((uint64_t) p[3] << 32)
	     | ((uint64_t) p[4] << 24) | ((uint64_t) p[5] << 16)
	     | ((uint64_t) p[6] << 8)  | ((uint64_t) p[7]);
}

static inline void store_be64(uint8_t *p, uint64_t v)
{
	p[0] = (uint8_t) (v >> 56); p[1] = (uint8_t) (v >> 48);
	p[2] = (uint8_t) (v >> 40); p[3] = (uint8_t) (v >> 32);
	p[4] = (uint8_t) (v >> 24); p[5] = (uint8_t) (v >> 16);
	p[6] = (uint8_t) (v >> 8);  p[7] = (uint8_t) v;
}

static inline uint64_t camellia_f(uint64_t fin, uint64_t ke)
{
	uint64_t x = fin ^ ke;
	return SP[0][(x >> 56) & 0xff] ^ SP[1][(x >> 48) & 0xff]
	     ^ SP[2][(x >> 40) & 0xff] ^ SP[3][(x >> 32) & 0xff]
	     ^ SP[4][(x >> 24) & 0xff] ^ SP[5][(x >> 16) & 0xff]
	     ^ SP[6][(x >>  8) & 0xff] ^ SP[7][ x        & 0xff];
}

static inline uint32_t rotl32(uint32_t v, int n)
{
	return (v << n) | (v >> (32 - n));
}

static inline uint64_t camellia_fl(uint64_t fin, uint64_t ke)
{
	uint32_t x1 = (uint32_t) (fin >> 32), x2 = (uint32_t) fin;
	uint32_t k1 = (uint32_t) (ke >> 32), k2 = (uint32_t) ke;

	x2 ^= rotl32(x1 & k1, 1);
	x1 ^= (x2 | k2);
	return ((uint64_t) x1 << 32) | x2;
}

static inline uint64_t camellia_flinv(uint64_t fin, uint64_t ke)
{
	uint32_t y1 = (uint32_t) (fin >> 32), y2 = (uint32_t) fin;
	uint32_t k1 = (uint32_t) (ke >> 32), k2 = (uint32_t) ke;

	y1 ^= (y2 | k2);
	y2 ^= rotl32(y1 & k1, 1);
	return ((uint64_t) y1 << 32) | y2;
}

/* the halves of a 128-bit value rotated left by n, 0 < n < 128 */
static void rotl128(uint64_t hi, uint64_t lo, int n, uint64_t *rhi, uint64_t *rlo)
{
	if (n >= 64) {
		uint64_t t = hi;
		hi = lo;
		lo = t;
		n -= 64;
	}
	if (n == 0) {
		*rhi = hi;
		*rlo = lo;
	} else {
		*rhi = (hi << n) | (lo >> (64 - n));
		*rlo = (lo << n) | (hi >> (64 - n));
	}
}

void crypton_camellia_init(crypton_camellia_key *ks, const uint8_t *key)
{
	uint64_t klhi = load_be64(key), kllo = load_be64(key + 8);
	uint64_t d1 = klhi, d2 = kllo, kahi, kalo, hi, lo;

	d2 ^= camellia_f(d1, SIGMA[0]);
	d1 ^= camellia_f(d2, SIGMA[1]);
	d1 ^= klhi;
	d2 ^= kllo;
	d2 ^= camellia_f(d1, SIGMA[2]);
	d1 ^= camellia_f(d2, SIGMA[3]);
	kahi = d1;
	kalo = d2;

	ks->kw[0] = klhi;
	ks->kw[1] = kllo;
	ks->k[0] = kahi;
	ks->k[1] = kalo;
	rotl128(klhi, kllo, 15, &hi, &lo);  ks->k[2] = hi;  ks->k[3] = lo;
	rotl128(kahi, kalo, 15, &hi, &lo);  ks->k[4] = hi;  ks->k[5] = lo;
	rotl128(kahi, kalo, 30, &hi, &lo);  ks->ke[0] = hi; ks->ke[1] = lo;
	rotl128(klhi, kllo, 45, &hi, &lo);  ks->k[6] = hi;  ks->k[7] = lo;
	rotl128(kahi, kalo, 45, &hi, &lo);  ks->k[8] = hi;
	rotl128(klhi, kllo, 60, &hi, &lo);  ks->k[9] = lo;
	rotl128(kahi, kalo, 60, &hi, &lo);  ks->k[10] = hi; ks->k[11] = lo;
	rotl128(klhi, kllo, 77, &hi, &lo);  ks->ke[2] = hi; ks->ke[3] = lo;
	rotl128(klhi, kllo, 94, &hi, &lo);  ks->k[12] = hi; ks->k[13] = lo;
	rotl128(kahi, kalo, 94, &hi, &lo);  ks->k[14] = hi; ks->k[15] = lo;
	rotl128(klhi, kllo, 111, &hi, &lo); ks->k[16] = hi; ks->k[17] = lo;
	rotl128(kahi, kalo, 111, &hi, &lo); ks->kw[2] = hi; ks->kw[3] = lo;
}

static void camellia_crypt(uint8_t *out, const uint64_t kw[4], const uint64_t k[18],
                           const uint64_t ke[4], const uint8_t *in, uint32_t nblocks)
{
	uint32_t i;

	for (i = 0; i < nblocks; i++) {
		uint64_t d1 = load_be64(in + 16 * i) ^ kw[0];
		uint64_t d2 = load_be64(in + 16 * i + 8) ^ kw[1];
		int base;

		for (base = 0; base <= 12; base += 6) {
			d2 ^= camellia_f(d1, k[base + 0]);
			d1 ^= camellia_f(d2, k[base + 1]);
			d2 ^= camellia_f(d1, k[base + 2]);
			d1 ^= camellia_f(d2, k[base + 3]);
			d2 ^= camellia_f(d1, k[base + 4]);
			d1 ^= camellia_f(d2, k[base + 5]);
			if (base == 0) {
				d1 = camellia_fl(d1, ke[0]);
				d2 = camellia_flinv(d2, ke[1]);
			} else if (base == 6) {
				d1 = camellia_fl(d1, ke[2]);
				d2 = camellia_flinv(d2, ke[3]);
			}
		}

		store_be64(out + 16 * i, d2 ^ kw[2]);
		store_be64(out + 16 * i + 8, d1 ^ kw[3]);
	}
}

void crypton_camellia_encrypt(uint8_t *out, const crypton_camellia_key *ks,
                              const uint8_t *in, uint32_t nblocks)
{
	camellia_crypt(out, ks->kw, ks->k, ks->ke, in, nblocks);
}

/* Decryption is the same rounds with the subkeys the other way round. */
void crypton_camellia_decrypt(uint8_t *out, const crypton_camellia_key *ks,
                              const uint8_t *in, uint32_t nblocks)
{
	uint64_t kw[4], k[18], ke[4];
	int i;

	kw[0] = ks->kw[2]; kw[1] = ks->kw[3]; kw[2] = ks->kw[0]; kw[3] = ks->kw[1];
	for (i = 0; i < 18; i++)
		k[i] = ks->k[17 - i];
	for (i = 0; i < 4; i++)
		ke[i] = ks->ke[3 - i];
	camellia_crypt(out, kw, k, ke, in, nblocks);
}
