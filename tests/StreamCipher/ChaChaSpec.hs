longKey :: ByteString
longKey = B.pack [fromIntegral (0x40 + i) | i <- [0 .. 31 :: Int]]

longNonce :: ByteString
longNonce = B.pack [fromIntegral (0xf0 - i) | i <- [0 .. 11 :: Int]]

longTests :: Spec
longTests = describe "long keystream" $ mapM_ test longVectors
  where
    test (counter, len, expected) =
        it (show len ++ " bytes from counter " ++ show counter) $ do
            digest (fst (ChaCha.generate st len) :: ByteString) `shouldBe` expected
            digest (fst (ChaCha.combine st (B.replicate len 0)) :: ByteString)
                `shouldBe` expected
      where
        st =
            ChaCha.setCounter32 counter $
                ChaCha.initialize 20 longKey longNonce
    digest bs = BA.convert (hash bs :: Digest SHA256) :: ByteString

-- The 32-bit counter carries into the word above it, which the bulk loops
-- must not do on their own account, so a message that runs over the carry
-- has to come out the same as the same message taken a block at a time.
counterCarry :: Spec
counterCarry =
    describe "counter carry" $
        mapM_ test [0xffffff00, 0xfffffff0, 0xfffffffe]
  where
    test counter =
        it ("crossing 2^32 from " ++ show (counter :: Word32)) $
            fst (ChaCha.combine st (B.replicate len 0))
                `shouldBe` B.concat (blockAtATime len st)
      where
        len = 8192
        st = ChaCha.setCounter32 counter (ChaCha.initialize 20 longKey longNonce)
        blockAtATime 0 _ = []
        blockAtATime n s =
            let (c, next) = ChaCha.combine s (B.replicate (min 64 n) 0)
             in c : blockAtATime (n - min 64 n) next

